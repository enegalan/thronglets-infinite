#!/usr/bin/env python3
"""Export one horizontal strip PNG per thronglet animation.

Writes:
  references/thronglet-anims/   (docs / R&D)
  resources/sprites/throng_anims/  (runtime source sheets)
  resources/sprites/throng_anims/manifest.json
"""

from __future__ import annotations

import importlib.util
import json
import os
import shutil

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF_DIR = os.path.join(ROOT, "references", "thronglet-anims")
RES_DIR = os.path.join(ROOT, "resources", "sprites", "throng_anims")
def _load_make_art():
    path = os.path.join(ROOT, "tools", "make_art.py")
    spec = importlib.util.spec_from_file_location("make_art", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _safe_name(clip: str) -> str:
    return clip.replace(" ", "_").replace("/", "_")


def _frame_images(frames):
    out = []
    for item in frames:
        if isinstance(item, tuple):
            out.append(item[0].convert("RGBA"))
        else:
            out.append(item.convert("RGBA"))
    return out


def _strip(frames: list[Image.Image]) -> tuple[Image.Image, int, int]:
    if not frames:
        return Image.new("RGBA", (1, 1), (0, 0, 0, 0)), 1, 1
    cell_w = max(img.size[0] for img in frames)
    cell_h = max(img.size[1] for img in frames)
    sheet = Image.new("RGBA", (cell_w * len(frames), cell_h), (0, 0, 0, 0))
    for i, img in enumerate(frames):
        x = i * cell_w + (cell_w - img.size[0]) // 2
        y = cell_h - img.size[1]
        sheet.alpha_composite(img, (x, y))
    return sheet, cell_w, cell_h


def _loose_singles(make_art):
    singles = (
        ("ThrongA_Default_Ghost", "Char_ThrongA_Default_Ghost.png"),
        ("Thronglet_Outline", "T_ThrongletOutline.png"),
        ("Throng_Outline", "T_ThrongOutline.png"),
    )
    extra = {}
    for clip, filename in singles:
        img = make_art._tex(filename)
        if img is None:
            continue
        extra[clip] = [img.convert("RGBA")]
    return extra


def _write_readme(folder: str, written: list[tuple[str, str, int]]) -> None:
    lines = [
        "# Thronglet animation strips",
        "",
        "One PNG per clip. Frames run left → right. Regenerated by `tools/export_throng_anims.py`.",
        "",
        "| Clip | Frames | File |",
        "| --- | ---: | --- |",
    ]
    for name, rel, count in written:
        lines.append(
            "| `%s` | %d | [%s](%s) |"
            % (name, count, os.path.basename(rel), os.path.basename(rel))
        )
    lines.append("")
    open(os.path.join(folder, "README.md"), "w").write("\n".join(lines))


def export() -> list[tuple[str, str, int]]:
    make_art = _load_make_art()
    clips = dict(make_art._load_throng_clips())
    clips.update(_loose_singles(make_art))
    for folder in (REF_DIR, RES_DIR):
        os.makedirs(folder, exist_ok=True)
    written = []
    manifest = {"clips": {}, "strip_dir": "res://resources/sprites/throng_anims/"}
    for name in sorted(clips):
        frames = _frame_images(clips[name])
        sheet, cell_w, cell_h = _strip(frames)
        safe = _safe_name(name) + ".png"
        for folder in (REF_DIR, RES_DIR):
            path = os.path.join(folder, safe)
            sheet.save(path)
        written.append((name, os.path.join("resources", "sprites", "throng_anims", safe), len(frames)))
        manifest["clips"][name] = {
            "file": safe,
            "frames": len(frames),
            "cell_w": cell_w,
            "cell_h": cell_h,
        }
    with open(os.path.join(RES_DIR, "manifest.json"), "w") as handle:
        json.dump(manifest, handle, indent=2, sort_keys=True)
        handle.write("\n")
    # Keep a copy next to the doc strips for the R&D folder.
    shutil.copy2(
        os.path.join(RES_DIR, "manifest.json"),
        os.path.join(REF_DIR, "manifest.json"),
    )
    _write_readme(REF_DIR, [(n, os.path.join("references", "thronglet-anims", _safe_name(n) + ".png"), c) for n, _r, c in written])
    _write_readme(RES_DIR, written)
    return written


if __name__ == "__main__":
    rows = export()
    print("wrote", len(rows), "strips to", RES_DIR, "and", REF_DIR)
